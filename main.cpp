#include <iostream>
#include <cmath>
#include <limits>

using namespace std;

// Функція для очищення потоку введення при помилкових даних
void clearInput() {
    cin.clear();
    cin.ignore(numeric_limits<streamsize>::max(), '\n');
}


// ЗАВДАННЯ 1: Алгоритми з розгалуженням (If18 та If27)

// Завдання 1.1 (If18): Знайти порядковий номер числа, відмінного від двох інших
void task1_part1() {
    cout << "\n--- Завдання 1.1 (If18) ---" << endl;
    int a, b, c;

    cout << "Введіть три цілих числа (два з яких рівні між собою): ";
    while (!(cin >> a >> b >> c)) {
        cout << "Помилка введення! Будь ласка, введіть три цілих числа: ";
        clearInput();
    }

    // Перевірка, яке саме число відрізняється від двох інших
    if (a == b && a != c) {
        cout << "Порядковий номер відмінного числа: 3 (число " << c << ")" << endl;
    } else if (a == c && a != b) {
        cout << "Порядковий номер відмінного числа: 2 (число " << b << ")" << endl;
    } else if (b == c && b != a) {
        cout << "Порядковий номер відмінного числа: 1 (число " << a << ")" << endl;
    } else {
        cout << "Помилка: Умови не дотримано (два числа мають бути рівними, а третє — відрізнятися)!" << endl;
    }
}

// Завдання 1.2 (If27): Обчислення значення ступенчастої функції f(x)
void task1_part2() {
    cout << "\n--- Завдання 1.2 (If27) ---" << endl;
    double x;

    cout << "Введіть дійсне число x: ";
    while (!(cin >> x)) {
        cout << "Помилка введення! Введіть дійсне число: ";
        clearInput();
    }

    int f;
    if (x < 0) {
        f = 0;
    } else {
        // Округлення до найближчого меншого цілого (floor)
        int k = static_cast<int>(floor(x));
        // Для парних інтервалів [0,1), [2,3)... f(x) = 1, для непарних — f(x) = -1
        if (k % 2 == 0) {
            f = 1;
        } else {
            f = -1;
        }
    }

    cout << "Значення функції f(" << x << ") = " << f << endl;
}

// Головна процедура Завдання 1
void task1() {
    cout << "\n==========================================" << endl;
    cout << "           ВИКОНАННЯ ЗАВДАННЯ 1           " << endl;
    cout << "==========================================" << endl;
    task1_part1();
    task1_part2();
}

// =====================================================================
// ЗАВДАННЯ 2: Перевірка попадання точки в зелену фігуру (Варіант 13)
// =====================================================================
void task2() {
    cout << "\n==========================================" << endl;
    cout << "           ВИКОНАННЯ ЗАВДАННЯ 2 (Варіант 13)" << endl;
    cout << "==========================================" << endl;

    double x, y, r;

    cout << "Введіть координату x: ";
    while (!(cin >> x)) {
        cout << "Помилка введення! Введіть число x: ";
        clearInput();
    }

    cout << "Введіть координату y: ";
    while (!(cin >> y)) {
        cout << "Помилка введення! Введіть число y: ";
        clearInput();
    }

    cout << "Введіть радіус r (r > 0): ";
    while (!(cin >> r) || r <= 0) {
        cout << "Помилка! Радіус r має бути додатним числом: ";
        clearInput();
    }

    // Варіант 13 (Зелена область):
    // 1. IV чверть: x >= 0 та y <= 0
    // 2. Усередині кола радіуса r: x*x + y*y <= r*r
    // 3. Вище або на прямій y = -x (тобто y >= -x)
    bool isInside = (x >= 0) && (y <= 0) && (x * x + y * y <= r * r) && (y >= -x);

    if (isInside) {
        cout << "Результат: Точка (" << x << ", " << y << ") ПОПАДАЄ в зелену область (Варіант 13)!" << endl;
    } else {
        cout << "Результат: Точка (" << x << ", " << y << ") НЕ попадає в зелену область." << endl;
    }
}

