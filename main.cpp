// ЗАВДАННЯ 3: Організація меню вибору за допомогою switch
// =====================================================================
void task3() {
    int choice;
    bool keepRunning = true;

    // Цикл для переключення між завданнями без перезапуску програми
    while (keepRunning) {
        cout << "\n==========================================" << endl;
        cout << "                ГОЛОВНЕ МЕНЮ              " << endl;
        cout << "==========================================" << endl;
        cout << "1. Виконати Завдання 1 (If18 та If27)" << endl;
        cout << "2. Виконати Завдання 2 (Варіант 13)" << endl;
        cout << "3. Завершити роботу програми" << endl;
        cout << "------------------------------------------" << endl;
        cout << "Оберіть пункт меню (1-3): ";

        if (!(cin >> choice)) {
            cout << "Помилка! Введіть ціле число від 1 до 3." << endl;
            clearInput();
            continue;
        }

        // Інструкція вибору switch за вимогою Завдання 3
        switch (choice) {
            case 1:
                task1();
                break;
            case 2:
                task2();
                break;
            case 3:
                cout << "Вихід з програми. До побачення!" << endl;
                keepRunning = false;
                break;
            default:
                cout << "Невірний вибір! Введіть число 1, 2 або 3." << endl;
                break;
        }
    }
}


int main() {
    // При запуске программы сразу же открывается меню (Задание 3)
    task3();
    return 0;
}
