#include <iostream>
#include <limits>

using namespace std;

// Очистка потока ввода при ошибках
void clearInput() {
    cin.clear();
    cin.ignore(numeric_limits<streamsize>::max(), '\n');
}

// =====================================================================
// ЗАДАНИЕ 1 (Объединяет If18 и If27 в одной функции)
// =====================================================================
void task1() {
    cout << "\n==========================================" << endl;
    cout << "           ВИКОНАННЯ ЗАВДАННЯ 1           " << endl;
    cout << "==========================================" << endl;

    // --- Часть 1 (If18) ---
    cout << "\n--- Завдання 1.1 (If18) ---" << endl;
    int a, b, c;
    cout << "Введіть три цілих числа (два з яких рівні): ";
    while (!(cin >> a >> b >> c)) {
        cout << "Помилка! Введіть три цілих числа: ";
        clearInput();
    }

    if (a == b && a != c) {
        cout << "Порядковий номер відмінного числа: 3 (число " << c << ")" << endl;
    } else if (a == c && a != b) {
        cout << "Порядковий номер відмінного числа: 2 (число " << b << ")" << endl;
    } else if (b == c && b != a) {
        cout << "Порядковий номер відмінного числа: 1 (число " << a << ")" << endl;
    } else {
        cout << "Помилка: Два числа мають бути рівними, а третє — відрізнятися!" << endl;
    }

    // --- Часть 2 (If27 через if-else) ---
    cout << "\n--- Завдання 1.2 (If27) ---" << endl;
    double x;
    cout << "Введіть дійсне число x: ";
    while (!(cin >> x)) {
        cout << "Помилка! Введіть дійсне число: ";
        clearInput();
    }

    int f;
    if (x < 0) {
        f = 0;
    } else {
        int intX = static_cast<int>(x);
        if (intX % 2 == 0) {
            f = 1;
        } else {
            f = -1;
        }
    }
    cout << "Значення функції f(" << x << ") = " << f << endl;
}

// =====================================================================
// ЗАДАНИЕ 2 (Вариант 13: Две зеленые области)
// =====================================================================
void task2() {
    cout << "\n==========================================" << endl;
    cout << "        ВИКОНАННЯ ЗАВДАННЯ 2 (Варіант 13) " << endl;
    cout << "==========================================" << endl;

    double x, y, r;

    cout << "Введіть координату x: ";
    while (!(cin >> x)) {
        cout << "Помилка! Введіть число x: ";
        clearInput();
    }

    cout << "Введіть координату y: ";
    while (!(cin >> y)) {
        cout << "Помилка! Введіть число y: ";
        clearInput();
    }

    cout << "Введіть радіус r (r > 0): ";
    while (!(cin >> r) || r <= 0) {
        cout << "Помилка! Радіус має бути додатним: ";
        clearInput();
    }

    // Область 1 (IV четверть: x >= 0, y <= 0, внутри круга и выше y = -x)
    bool region1 = (x >= 0) && (y <= 0) && (x * x + y * y <= r * r) && (y >= -x);

    // Область 2 (III четверть: x <= 0, y <= 0, внутри круга и правее x = -r/2)
    bool region2 = (x <= 0) && (y <= 0) && (x * x + y * y <= r * r) && (x >= -r / 2.0);

    if (region1 || region2) {
        cout << "Результат: Точка (" << x << ", " << y << ") ПОПАДАЄ в зелену область!" << endl;
    } else {
        cout << "Результат: Точка (" << x << ", " << y << ") НЕ попадає в зелену область." << endl;
    }
}

// =====================================================================
// ЗАДАНИЕ 3 (Главное меню через switch)
// =====================================================================
void task3() {
    int choice;
    bool keepRunning = true;

    while (keepRunning) {
        cout << "\n==========================================" << endl;
        cout << "                ГОЛОВНЕ МЕНЮ              " << endl;
        cout << "==========================================" << endl;
        cout << "1. Виконати Завдання 1 (If18 та If27)" << endl;
        cout << "2. Виконати Завдання 2 (Варіант 13)" << endl;
        cout << "3. Завершити роботу програми" << endl;
        cout << "------------------------------------------" << endl;
        cout << "Оберіть пункт меню (1-3): ";

        if (!(cin >> choice)) {
            cout << "Помилка! Введіть ціле число від 1 до 3." << endl;
            clearInput();
            continue;
        }

        switch (choice) {
            case 1:
                task1();
                break;
            case 2:
                task2();
                break;
            case 3:
                cout << "Вихід з програми. До побачення!" << endl;
                keepRunning = false;
                break;
            default:
                cout << "Невірний вибір! Введіть 1, 2 або 3." << endl;
                break;
        }
    }
}

// =====================================================================
// ЕДИНАЯ ТОЧКА ВХОДА (ОДИН main)
// =====================================================================
int main() {
    task3();
    return 0;
}
